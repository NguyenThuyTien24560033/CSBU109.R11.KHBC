import swaggerJSDoc from 'swagger-jsdoc';
import swaggerUi from 'swagger-ui-express';

const options = {
    definition: {
        openapi: '3.0.0',
        info: {
            title: 'RESTful API Documentation - Web & Database Lab 3',
            version: '1.0.0',
            description: 'Interactive API documentation auto-generated by Swagger UI for Ecommerce Orders'
        },
        servers: [
            {
                url: 'http://localhost:3000/api/v1',
                description: 'Development Local Server'
            }
        ]
    },
    apis: ['./routes/*.js']
};

const swaggerSpec = swaggerJSDoc(options);

const setupSwagger = (app) => {
    app.use('/api-docs', swaggerUi.serve, swaggerUi.setup(swaggerSpec));
    console.log('Swagger UI documentation is ready at: http://localhost:3000/api-docs');
};

export default setupSwagger;